"""
routers/analytics_interpret.py — Context-Aware AI Interpretation Engine

POST /analytics/interpret
  Receives the computed output from any Advanced Analytics module,
  plus org/dataset context, and returns a structured 7-section
  natural-language interpretation generated by the LLM.

The LLM only explains; it never re-computes statistics.
Statistical values come exclusively from the caller.

POST /analytics/interpret/followup
  Continue the conversation with a follow-up question about the
  most recent interpretation.
"""

import os
import json
import logging
from typing import Optional, Dict, Any, List

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel

from auth import get_current_user
from dependencies import get_current_org, get_org_connection_string
from models import get_db

logger = logging.getLogger(__name__)
router = APIRouter()

# ── Pydantic ──────────────────────────────────────────────────────────────────

class InterpretRequest(BaseModel):
    module: str                     # "forecast" | "anomaly" | "correlation" | "cluster"
                                    # | "regression" | "classification" | "pca" | "hypothesis"
    results: Dict[str, Any]         # the actual computed output — stats, matrix, clusters, etc.
    dataset_meta: Optional[Dict[str, Any]] = None   # {table, columns, description}
    objective:   Optional[str] = None               # user's stated goal / question
    extra_context: Optional[str] = None             # any extra info the UI passes

class FollowUpRequest(BaseModel):
    module: str
    results: Dict[str, Any]
    previous_interpretation: Dict[str, Any]
    question: str
    dataset_meta: Optional[Dict[str, Any]] = None
    extra_context: Optional[str] = None


# ── LLM call helper ───────────────────────────────────────────────────────────

def _get_llm_client():
    """Return an openai-compatible client using the platform's LLM key."""
    try:
        import openai
        api_key = (
            os.environ.get("OPENAI_API_KEY") or
            os.environ.get("ANTHROPIC_API_KEY") or
            os.environ.get("LLM_API_KEY", "")
        )
        base_url = os.environ.get("LLM_BASE_URL") or None
        if base_url:
            return openai.OpenAI(api_key=api_key, base_url=base_url)
        return openai.OpenAI(api_key=api_key)
    except ImportError:
        return None


def _call_llm(messages: list, model: str = "gpt-4o-mini", temperature: float = 0.3) -> str:
    client = _get_llm_client()
    if client is None:
        raise RuntimeError("LLM library not available. Install openai.")
    resp = client.chat.completions.create(
        model=model,
        messages=messages,
        temperature=temperature,
        max_tokens=1800,
    )
    return resp.choices[0].message.content.strip()


# ── Module-specific prompts ───────────────────────────────────────────────────

MODULE_GUIDE = {
    "forecast": """
You are interpreting a **Time Series Forecast** result.
Focus on:
- Direction and magnitude of the historical trend (increasing/declining/stable).
- Seasonality or recurring patterns if visible in the stats.
- What the forecast predicts and over what horizon.
- Confidence interval width — wide CI = high uncertainty, say so.
- Likely operational/financial implications for the organization.
""",
    "anomaly": """
You are interpreting an **Anomaly Detection** result.
Focus on:
- Number of anomalies detected and what percentage of data they represent.
- When/where the anomalies occurred (if temporal info is present).
- How they differ from normal patterns (magnitude, direction).
- Potential operational causes — clearly distinguish possible causes from confirmed facts.
- Whether the anomalies warrant immediate investigation.
""",
    "correlation": """
You are interpreting a **Correlation Analysis** result (Pearson/Spearman/Kendall matrix).
Focus on:
- The strongest positive and negative correlations.
- Variables with weak or no meaningful association.
- Always distinguish correlation from causation.
- Relationships that could have operational or strategic significance.
- Pairs worth deeper investigation via regression or controlled study.
""",
    "cluster": """
You are interpreting a **Cluster Analysis (K-Means)** result.
Focus on:
- Number of clusters identified and their defining characteristics.
- What differentiates one cluster from another (centroid values, spread).
- Potential business meaning of each segment.
- How the organization could use these segments operationally.
- Cluster quality (inertia / silhouette if provided).
""",
    "regression": """
You are interpreting a **Regression Analysis** result.
Focus on:
- Relationship between independent variables and the target.
- Direction and magnitude of coefficients.
- R² / RMSE — how much variance is explained.
- Statistical significance (p-values) if provided.
- Practical vs statistical significance.
- Always note that regression shows association, not causation.
""",
    "classification": """
You are interpreting a **Classification Model** result.
Focus on:
- Overall accuracy, precision, recall, F1 per class.
- Which classes are harder to predict (lower recall).
- The cost of false positives vs false negatives in the business context.
- What the model predicts and how reliable that prediction is.
- Practical implications of prediction errors.
""",
    "pca": """
You are interpreting a **Principal Component Analysis (PCA)** result.
Focus on:
- How much cumulative variance the top components explain.
- Which original variables load most heavily on each component.
- What the components might represent conceptually.
- Information lost (variance not captured).
- How the reduced representation supports downstream analysis.
""",
    "hypothesis": """
You are interpreting a **Statistical Hypothesis Test** result.
Focus on:
- The null and alternative hypotheses.
- Test statistic and p-value.
- Whether the null hypothesis can be rejected at the stated α level.
- Effect size — distinguish statistical from practical significance.
- Confidence intervals if present.
- What the finding means for the organization's decision.
""",
}

MODULE_DEFAULT = """
You are interpreting an advanced analytics result.
Explain what the result shows, what it means for the organization, and what actions to consider.
"""


def _build_system_prompt(module: str, org_name: str, industry: str) -> str:
    guide = MODULE_GUIDE.get(module.lower(), MODULE_DEFAULT)
    return f"""You are Vantage AI's analytical interpretation engine. Your role is to explain
advanced analytics results in clear, context-specific business language.

Organisation: {org_name}
Industry: {industry}

{guide}

IMPORTANT RULES:
1. Only use the statistical values provided to you. Do not invent numbers, forecasts, or metrics.
2. Distinguish clearly: correlation ≠ causation, forecast ≠ certainty, anomaly ≠ confirmed problem.
3. If key organizational context is missing, state your assumptions explicitly.
4. Keep each section concise but informative — aim for 2–4 sentences per section.
5. Write for a business audience, not a data science audience.

Respond ONLY with valid JSON matching this exact schema:
{{
  "executive_summary": "...",
  "what_results_show": "...",
  "org_context": "...",
  "key_findings": ["...", "..."],
  "implications": "...",
  "recommendations": ["...", "..."],
  "limitations": "..."
}}"""


def _build_user_message(module: str, results: dict, dataset_meta: dict, objective: str, extra_context: str) -> str:
    parts = [
        f"Analytical module: {module}",
        f"Computed results:\n{json.dumps(results, indent=2, default=str)[:3000]}",
    ]
    if dataset_meta:
        parts.append(f"Dataset metadata:\n{json.dumps(dataset_meta, indent=2, default=str)[:800]}")
    if objective:
        parts.append(f"User's objective / question: {objective}")
    if extra_context:
        parts.append(f"Additional context: {extra_context}")
    return "\n\n".join(parts)


# ── Org context helper ────────────────────────────────────────────────────────

def _get_org_context(org) -> tuple[str, str]:
    """Return (org_name, industry) from the org object."""
    org_name = getattr(org, "name", None) or getattr(org, "org_name", None) or "this organization"
    industry = "unknown industry"
    # Try to read industry from org metadata if it exists
    meta = getattr(org, "metadata", None) or getattr(org, "meta", None)
    if isinstance(meta, str):
        try:
            meta = json.loads(meta)
        except Exception:
            meta = {}
    if isinstance(meta, dict):
        industry = meta.get("industry") or meta.get("sector") or industry
    return org_name, industry


def _parse_llm_json(raw: str) -> dict:
    """Extract the JSON object from the LLM response (handles markdown code fences)."""
    import re
    # strip ```json ... ``` fences
    cleaned = re.sub(r"```(?:json)?\s*", "", raw).strip().rstrip("`").strip()
    return json.loads(cleaned)


# ── Routes ────────────────────────────────────────────────────────────────────

@router.post("/analytics/interpret")
async def interpret_analysis(
    body: InterpretRequest,
    org=Depends(get_current_org),
    user=Depends(get_current_user),
):
    """
    Generate a structured AI interpretation of a completed analytics result.
    Returns a 7-section JSON interpretation.
    """
    org_name, industry = _get_org_context(org)
    system_prompt = _build_system_prompt(body.module, org_name, industry)
    user_message  = _build_user_message(
        body.module,
        body.results,
        body.dataset_meta or {},
        body.objective or "",
        body.extra_context or "",
    )

    try:
        raw = _call_llm(
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user",   "content": user_message},
            ]
        )
        interpretation = _parse_llm_json(raw)
    except RuntimeError as e:
        raise HTTPException(503, f"LLM unavailable: {e}")
    except (json.JSONDecodeError, ValueError) as e:
        logger.warning("LLM returned non-JSON for %s: %s", body.module, e)
        # Return raw text wrapped in structure so the UI still renders
        interpretation = {
            "executive_summary":   raw[:500],
            "what_results_show":   "",
            "org_context":         "",
            "key_findings":        [],
            "implications":        "",
            "recommendations":     [],
            "limitations":         "Response could not be structured automatically.",
        }
    except Exception as e:
        logger.error("Interpretation failed: %s", e, exc_info=True)
        raise HTTPException(500, f"Interpretation failed: {e}")

    return {
        "module":         body.module,
        "org_name":       org_name,
        "industry":       industry,
        "interpretation": interpretation,
    }


@router.post("/analytics/interpret/followup")
async def followup_question(
    body: FollowUpRequest,
    org=Depends(get_current_org),
    user=Depends(get_current_user),
):
    """
    Answer a follow-up question about an already-interpreted analytics result.
    Uses the original results and prior interpretation as context.
    """
    org_name, industry = _get_org_context(org)

    system_prompt = f"""You are Vantage AI's analytical assistant for {org_name} ({industry}).
You have already produced an interpretation of a {body.module} analysis.
Now answer the user's follow-up question using the original analytical results and your prior interpretation as context.
Be specific, grounded in the data provided, and avoid fabricating values.
If the question cannot be answered from the available data, say so clearly."""

    prior = json.dumps(body.previous_interpretation, indent=2, default=str)[:1500]
    results_str = json.dumps(body.results, default=str)[:2000]
    dataset_meta_str = json.dumps(body.dataset_meta or {}, default=str)[:600]

    user_message = f"""Original results:
{results_str}

Dataset metadata:
{dataset_meta_str}

Prior interpretation:
{prior}

Follow-up question: {body.question}"""

    try:
        answer = _call_llm(
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user",   "content": user_message},
            ],
            temperature=0.4,
        )
    except RuntimeError as e:
        raise HTTPException(503, f"LLM unavailable: {e}")
    except Exception as e:
        logger.error("Follow-up failed: %s", e, exc_info=True)
        raise HTTPException(500, f"Follow-up failed: {e}")

    return {"answer": answer}
