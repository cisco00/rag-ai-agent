/**
 * SharedView — public, unauthenticated page for viewing a shared report.
 *
 * Rendered when the browser URL matches /shared/<report_id>.
 * Fetches GET /shared/<id> (no auth required) and displays the
 * query, AI response text and optional visualization.
 */
import { useEffect, useState } from 'react';
import { BarChart2, AlertCircle, Loader2, Share2, Calendar } from 'lucide-react';
import { ChartDisplay } from './ChartDisplay';

interface SharedReport {
  query: string;
  response: string;
  visualization?: any;
  created_at: string;
}

interface SharedViewProps {
  reportId: string;
}

export function SharedView({ reportId }: SharedViewProps) {
  const [report, setReport] = useState<SharedReport | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    const apiBase =
      (window as any).__VANTAGE_API_URL__ ||
      (import.meta as any).env?.VITE_API_URL ||
      'http://localhost:8000';

    fetch(`${apiBase}/shared/${encodeURIComponent(reportId)}`)
      .then(async (res) => {
        if (!res.ok) {
          const body = await res.json().catch(() => ({}));
          throw new Error(body.detail || `Error ${res.status}`);
        }
        return res.json();
      })
      .then((data) => setReport(data))
      .catch((err) => setError(err.message || 'Failed to load report'))
      .finally(() => setLoading(false));
  }, [reportId]);

  const formatDate = (iso: string) => {
    try {
      return new Intl.DateTimeFormat(undefined, {
        dateStyle: 'medium',
        timeStyle: 'short',
      }).format(new Date(iso));
    } catch {
      return iso;
    }
  };

  return (
    <div className="min-h-screen bg-gray-50">
      {/* Minimal top bar */}
      <header className="bg-white border-b border-gray-200 px-6 py-4 flex items-center gap-3">
        <BarChart2 className="size-6 text-blue-600" />
        <span className="font-semibold text-gray-900 text-lg">Vantage AI</span>
        <span className="ml-auto flex items-center gap-1.5 text-xs text-gray-400 bg-gray-100 px-3 py-1 rounded-full">
          <Share2 className="size-3" />
          Shared Report
        </span>
      </header>

      <main className="max-w-4xl mx-auto px-4 py-10 space-y-6">
        {loading && (
          <div className="flex flex-col items-center justify-center py-24 text-gray-400 gap-4">
            <Loader2 className="size-10 animate-spin text-blue-500" />
            <p className="text-sm">Loading report…</p>
          </div>
        )}

        {!loading && error && (
          <div className="flex items-start gap-3 p-6 bg-red-50 border border-red-200 rounded-xl text-red-700">
            <AlertCircle className="size-5 mt-0.5 shrink-0" />
            <div>
              <p className="font-semibold">Report not available</p>
              <p className="text-sm mt-1">{error}</p>
            </div>
          </div>
        )}

        {!loading && report && (
          <>
            {/* Query card */}
            <div className="bg-white rounded-xl border border-gray-200 shadow-sm p-6">
              <p className="text-xs font-semibold uppercase tracking-wide text-gray-400 mb-2">Query</p>
              <p className="text-gray-900 text-base font-medium">{report.query}</p>
              {report.created_at && (
                <p className="mt-3 flex items-center gap-1.5 text-xs text-gray-400">
                  <Calendar className="size-3.5" />
                  Shared on {formatDate(report.created_at)}
                </p>
              )}
            </div>

            {/* Visualization */}
            {report.visualization && (
              <div className="bg-white rounded-xl border border-gray-200 shadow-sm p-6">
                <p className="text-xs font-semibold uppercase tracking-wide text-gray-400 mb-4">Visualization</p>
                <ChartDisplay visualization={report.visualization} />
              </div>
            )}

            {/* AI response */}
            <div className="bg-white rounded-xl border border-gray-200 shadow-sm p-6">
              <p className="text-xs font-semibold uppercase tracking-wide text-gray-400 mb-3">Analysis</p>
              <div className="prose prose-sm max-w-none text-gray-700 whitespace-pre-wrap leading-relaxed">
                {report.response}
              </div>
            </div>

            <p className="text-center text-xs text-gray-400 pt-2">
              This report was generated by Vantage AI and shared as a read-only link.
            </p>
          </>
        )}
      </main>
    </div>
  );
}
